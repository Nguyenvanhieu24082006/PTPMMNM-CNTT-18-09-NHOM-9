// Chức năng tìm kiếm gợi ý thời gian thực (Live Search Autocomplete)
(function() {
    const input = document.getElementById('headerSearchInput');
    const dropdown = document.getElementById('headerSearchDropdown');
    let timeout = null;

    if (!input || !dropdown) return;

    input.addEventListener('input', function() {
        clearTimeout(timeout);
        const query = this.value.trim();
        if (query.length < 1) {
            dropdown.style.display = 'none';
            dropdown.innerHTML = '';
            return;
        }

        timeout = setTimeout(function() {
            fetch('/search-suggest.php?q=' + encodeURIComponent(query))
                .then(res => res.json())
                .then(data => {
                    if (!data.results || data.results.length === 0) {
                        dropdown.innerHTML = '<div style="padding: 16px 20px; text-align: center; color: #94a3b8; font-size: 0.875rem;">Không tìm thấy sản phẩm nào khớp với "<strong>' + escapeHtml(query) + '</strong>"</div>';
                        dropdown.style.display = 'block';
                        return;
                    }

                    let html = '';
                    data.results.forEach(item => {
                        html += `
                            <a href="${item.url}" class="vip-search-item">
                                <img src="${item.image}" alt="${escapeHtml(item.name)}" class="vip-search-item-img">
                                <div class="vip-search-item-info">
                                    <div class="vip-search-item-title">${escapeHtml(item.name)}</div>
                                    <div class="vip-search-item-cat">${escapeHtml(item.category)} • <span style="color: ${item.available > 0 ? '#4ade80' : '#ef4444'}">${item.available > 0 ? 'Còn ' + item.available + ' cái' : 'Hết hàng'}</span></div>
                                </div>
                                <div class="vip-search-item-price">${item.price}</div>
                            </a>
                        `;
                    });

                    if (data.total > data.results.length) {
                        html += `
                            <a href="/index.php?q=${encodeURIComponent(query)}" class="vip-search-view-all">
                                Xem tất cả ${data.total} sản phẩm cho "${escapeHtml(query)}" ➔
                            </a>
                        `;
                    }

                    dropdown.innerHTML = html;
                    dropdown.style.display = 'block';
                })
                .catch(() => {
                    dropdown.style.display = 'none';
                });
        }, 180);
    });

    document.addEventListener('click', function(e) {
        if (!e.target.closest('.vip-search-wrapper')) {
            dropdown.style.display = 'none';
        }
    });

    input.addEventListener('focus', function() {
        if (this.value.trim().length >= 1 && dropdown.innerHTML.trim() !== '') {
            dropdown.style.display = 'block';
        }
    });

    function escapeHtml(str) {
        if (!str) return '';
        return String(str)
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;')
            .replace(/'/g, '&#039;');
    }
})();
